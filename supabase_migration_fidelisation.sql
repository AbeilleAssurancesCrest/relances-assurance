CREATE TABLE IF NOT EXISTS public.suivis_fidelisation (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id bigint,
    nom text NOT NULL,
    prenom text NOT NULL DEFAULT '',
    email text NOT NULL DEFAULT '',
    telephone text NOT NULL DEFAULT '',
    statut text NOT NULL DEFAULT 'RI demandé',
    date_demande date NOT NULL DEFAULT CURRENT_DATE,
    date_recontact date,
    notes text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.suivis_fidelisation ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.suivis_fidelisation TO anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.suivis_fidelisation_id_seq TO anon, authenticated;

CREATE POLICY "Accès suivi fidélisation depuis l’application"
ON public.suivis_fidelisation
FOR ALL TO anon, authenticated
USING (true)
WITH CHECK (true);
